import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { launch, serve, check, done } from "./lib.mjs";

const root = path.resolve(new URL("..", import.meta.url).pathname);
const { server, url } = await serve(root);
const browser = await launch();
const errors = [];
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "payout-ret-"));
const open = async (ctx, hash = "") => { const p = await ctx.newPage(); p.on("pageerror", (e) => errors.push(e.message)); p.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); }); await p.goto(url + hash); await p.waitForFunction(() => document.documentElement.dataset.ready); return p; };
const gate = (p) => p.getAttribute("body", "data-gate");
const gone = (p) => p.waitForSelector("body > dialog:not(#settings)", { state: "detached" });
const view = (p) => p.evaluate(() => [...document.querySelectorAll(".view")].find((v) => !v.hidden)?.dataset.view);
const add = async (p, t, n) => { await p.fill("#tk", t); await p.fill("#sh", String(n)); await p.click("#addBtn"); };
const settle = (p) => p.waitForFunction(() => /Device\s+saved/.test(document.querySelector("#status").innerText));
const keys = (p) => p.evaluate(async () => new Promise((res) => { const q = indexedDB.open("payoutlab"); q.onsuccess = () => { const t = q.result.transaction("kv").objectStore("kv").getAllKeys(); t.onsuccess = () => res(t.result); }; }));

console.log("1. first visit: a clear choice, then Continue on every return");
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
let p = await open(ctx);
check("first visit shows the start screen", (await gate(p)) === "first" && (await p.isVisible("#gName")));
check("remember is offered, on by default, with an honest caption", (await p.isChecked("#gRem")) && /Kept only in this browser/.test(await p.innerText("#startBody")));
check("nothing is stored just for looking", !(await keys(p)).some((k) => String(k).startsWith("p:")));
await p.click('[data-g="bookmark"]'); await p.waitForSelector("dialog[open]");
const bm = await p.innerText("dialog[open]");
check("bookmark help is manual instructions, not a promise", /press Ctrl\+D|Ctrl\s*\+\s*D/i.test(bm) && /Add to Home Screen/.test(bm) && /cannot bring your portfolio back/.test(bm), bm.slice(0, 400));
check("bookmark link is shown and selectable", (await p.inputValue("#bmUrl")).startsWith(url));
await p.click('dialog[open] [data-result="done"]'); await gone(p);
await p.fill("#gName", "Retirement income");
await p.click('[data-g="start"]'); await p.waitForSelector("#view-portfolio:not([hidden])");
check("Start names the portfolio and opens Portfolio", (await p.innerText("#pname")) === "Retirement income");
await add(p, "SCHD", 120); await add(p, "O", 40);
await settle(p);
check("it is now remembered on this device", (await keys(p)).some((k) => String(k).startsWith("p:")));
await p.goto(url); await p.waitForFunction(() => document.documentElement.dataset.ready);
check("return visit shows Continue with the portfolio name", (await gate(p)) === "returning" && /Continue\s+Retirement income/.test(await p.innerText("#startBody")));
const sb = await p.innerText("#startBody");
check("it shows holdings, last edited and last packet time", /2 holdings/.test(sb) && /edited/.test(sb) && /last saved to a packet never/.test(sb), sb);
check("Continue is focused for keyboard users", await p.evaluate(() => document.activeElement?.id === "gContinue"));
await p.keyboard.press("Enter"); await p.waitForSelector("#view-overview:not([hidden])");
check("Continue opens the remembered portfolio", !(await gate(p)) && /\$/.test(await p.innerText("#roYear")) && (await p.innerText("#pname")) === "Retirement income");

console.log("2. deep links and bookmarks with a view skip the start screen");
const q = await open(ctx, "#/lab");
check("a bookmark to a view opens the last portfolio directly", !(await gate(q)) && (await view(q)) === "lab" && (await q.innerText("#pname")) === "Retirement income");
await q.close();

console.log("3. several portfolios stay distinct");
await p.close(); p = await open(ctx);
await p.click('[data-g="new"]'); await p.waitForSelector("dialog[open] input");
await p.fill("dialog[open] input", "Kids IRA"); await p.press("dialog[open] input", "Enter"); await gone(p);
await p.waitForSelector("#view-portfolio:not([hidden])");
await add(p, "KO", 10); await settle(p);
await p.goto(url); await p.waitForFunction(() => document.documentElement.dataset.ready);
check("the most recent portfolio is offered first", /Continue\s+Kids IRA/.test(await p.innerText("#startBody")));
check("the other portfolio is listed", /Retirement income/.test(await p.innerText("#startBody")));
await p.click('[data-g^="open:"]'); await p.waitForSelector("#view-overview:not([hidden])");
check("opening it switches portfolio", (await p.innerText("#pname")) === "Retirement income");
check("distinct holdings", (await p.$$eval("#rows .hrow", (r) => r.length)) === 2);
await p.close();

console.log("4. guest mode remembers nothing");
const g = await browser.newContext({ viewport: { width: 1280, height: 900 } });
let gp = await open(g);
await gp.fill("#gName", "Guest run"); await gp.uncheck("#gRem"); await gp.click('[data-g="start"]'); await gp.waitForSelector("#view-portfolio:not([hidden])");
await add(gp, "SCHD", 5);
check("status says it is not remembered", /Device\s+off/.test(await gp.innerText("#status")));
check("nothing is stored", !(await keys(gp)).some((k) => String(k).startsWith("p:")));
let warned = false;
gp.once("dialog", async (d) => { warned = d.type() === "beforeunload"; await d.accept(); });
await gp.goto(url).catch(() => {});
check("leaving a guest session with unsaved work warns first", warned);
await gp.waitForFunction(() => document.documentElement.dataset.ready).catch(() => {});
check("a reload starts fresh (first-run again)", (await gate(gp)) === "first");
await g.close();

console.log("5. storage unavailable (private mode style)");
const dn = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await dn.addInitScript(() => { Object.defineProperty(window, "indexedDB", { value: undefined }); Storage.prototype.setItem = () => { throw new DOMException("denied", "SecurityError"); }; });
const dp = await open(dn);
check("the start screen explains storage is blocked", /isn't letting the site remember data/.test(await dp.innerText("#startBody")));
check("there is no remember checkbox to mislead", !(await dp.$("#gRem")));
await dp.click('[data-g="start"]'); await dp.waitForSelector("#view-portfolio:not([hidden])");
await add(dp, "SCHD", 3);
const [d1] = await Promise.all([dp.waitForEvent("download"), dp.click("#saveBtn")]);
const pk = path.join(tmp, "denied.payout"); await d1.saveAs(pk);
check("packets still work", fs.statSync(pk).size > 400);
await dn.close();

console.log("6. cleared site data: only a packet brings the portfolio back");
const c1 = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const a = await open(c1);
await a.click('[data-g="start"]'); await a.waitForSelector("#view-portfolio:not([hidden])");
await add(a, "SCHD", 77); await settle(a);
const [d2] = await Promise.all([a.waitForEvent("download"), a.click("#saveBtn")]);
const pk2 = path.join(tmp, "mine.payout"); await d2.saveAs(pk2);
await a.evaluate(async () => { localStorage.clear(); await new Promise((r) => { const x = indexedDB.deleteDatabase("payoutlab"); x.onsuccess = x.onerror = x.onblocked = () => r(); }); });
await a.close();
const b = await open(c1);
check("after clearing site data the start screen is first-run, not a false Continue", (await gate(b)) === "first");
await b.setInputFiles("#fileIn", pk2); await b.waitForSelector("dialog[open]");
check("opening the packet shows what it contains first", /Open this packet\?/.test(await b.innerText("dialog[open]")));
await b.click('dialog[open] [data-result="open-new"]'); await gone(b);
await b.waitForSelector("#view-overview:not([hidden])");
check("packet restores the portfolio and leaves the start screen", !(await gate(b)) && (await b.$$eval("#rows .hrow", (r) => r.length)) === 1);
await c1.close();

console.log("7. persistence request is optional");
const c2 = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await c2.addInitScript(() => { Object.defineProperty(navigator, "storage", { value: { persist: () => Promise.reject(new Error("refused")), persisted: () => Promise.resolve(false) } }); });
const e = await open(c2);
await e.click('[data-g="start"]'); await e.waitForSelector("#view-portfolio:not([hidden])");
await add(e, "SCHD", 1); await settle(e);
check("a refused persistence request never blocks saving", (await keys(e)).some((k) => String(k).startsWith("p:")));
await e.click("#settingsBtn"); await e.waitForSelector("#settings[open]");
const note = await e.innerText("#storageNote");
check("settings say the browser may remove data, and that sync does not sync portfolios", /may remove this data/.test(note) && /does not sync this portfolio/.test(note), note);
await c2.close();

console.log("8. layout on a phone");
const m = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const mp = await open(m);
check("start screen fits without sideways scrolling", await mp.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
check("primary action is a comfortable touch target", (await mp.$eval('[data-g="start"]', (e) => e.getBoundingClientRect().height)) >= 44);
await m.close();

check("no console or page errors", errors.length === 0, errors.join(" | "));
await browser.close(); server.close(); done();
